my_string = 'hello World'

# print(dir(my_string)) <== this method shows all the properties and methods of the variable

print(my_string.upper()) # Set the var to Uppercase
print(my_string.lower()) # Set the var to Lowercase
print(my_string.swapcase()) # Invert the case
print(my_string.capitalize()) # Set the first caracter to Uppercase
print(my_string.replace('hello', 'bye')) # replace the first parameter with the second
print(len(my_string)) # Shows the number of caracters