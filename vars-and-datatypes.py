# ---- Variables ----

# Set a normar variable
my_var = 'something'

# Set mutiples vars
x, y, z = "x value", 'y value', "z value"

# Set a constant (unwritten rule)
MY_CONSTANT = 'something'

# Conventions
some_variable = 'asd' # Snake Case
someVariable = 'asd' # Camel Case
SomeVariable = 'asd' # Pascal Case

# ---- Data types ----

#1 Strings
string = 'first string';
print('1', type(string));

#2 Integer
int = 3
print('2', type(int));

#3 Float
float = 5.44
print('3', type(float));

#4 Boolean
boolean = True
print('4', type(boolean));

#5 None (Null)
none = None
print('5', type(none));

#6 List (Arrays)
list = ['string type', 763, False, 3.1416]
print('6', type(list));

#7 Tuples (const list / array)
tuple = ('another string', 69, True, None)
print('7', type(tuple));

#8 Dictionary (something like objets or json in js)
dict = {"name": 'Zaphkiel', "lastname": 'Urquidez', "Age": 17, "isAmazing": True}
print('8', type(dict));





